function [lhs, rhs] = static_resid(y, x, params)
T = NaN(3, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = 1/((1+y(10))*y(8))*1/(1+params(1));
T(2) = y(5)^params(4);
T(3) = y(4)^(1-params(4));
lhs(1) = 1/((1+y(10))*y(8));
rhs(1) = T(1)*(1+y(2)-params(2));
lhs(2) = params(6)/(1-y(4));
rhs(2) = y(3)/((1+y(10))*y(8));
lhs(3) = y(7);
rhs(3) = y(1)*T(2)*T(3);
lhs(4) = y(3);
rhs(4) = y(7)*(1-params(4))/y(4);
lhs(5) = y(2);
rhs(5) = y(7)*params(4)/y(5);
lhs(6) = y(5);
rhs(6) = y(5)*(1-params(2))+y(6);
lhs(7) = y(7);
rhs(7) = y(8)+y(6)+y(9);
lhs(8) = y(9);
rhs(8) = y(10)*y(8);
lhs(9) = y(1);
rhs(9) = y(1)^params(5);
lhs(10) = y(10);
rhs(10) = x(1);
end
