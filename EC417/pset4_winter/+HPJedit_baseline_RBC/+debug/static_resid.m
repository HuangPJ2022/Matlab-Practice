function [lhs, rhs] = static_resid(y, x, params)
T = NaN(5, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = 1/y(8);
T(2) = (y(9)*y(5))^params(4);
T(3) = y(4)^(1-params(4));
T(4) = (y(9)*y(5))^(params(4)-1);
T(5) = y(4)^(-params(4));
lhs(1) = T(1);
rhs(1) = T(1)*params(1)*(1+y(2)*y(9)-y(10));
lhs(2) = y(4);
rhs(2) = (y(3)/y(8))^params(7);
lhs(3) = y(7);
rhs(3) = y(1)*T(2)*T(3);
lhs(4) = y(7);
rhs(4) = y(8)+y(6);
lhs(5) = y(5);
rhs(5) = y(6)+y(5)*(1-y(10));
lhs(6) = y(1);
rhs(6) = y(1)^params(5)*exp(x(1));
lhs(7) = y(2);
rhs(7) = T(3)*y(1)*params(4)*T(4);
lhs(8) = y(2);
rhs(8) = params(2)*params(6)*y(9)^(params(6)-1);
lhs(9) = y(3);
rhs(9) = T(2)*y(1)*(1-params(4))*T(5);
lhs(10) = y(10);
rhs(10) = params(2)*y(9)^params(6);
end
